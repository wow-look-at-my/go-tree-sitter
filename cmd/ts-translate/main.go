func (e *emitter) emitLanguage() {
	e.printf("var language = ts.Language{\n")
	for cField, goField := range languageFields {
		if v, ok := e.file.lang[cField]; ok && v.isNum {
			e.printf("\t%s: %d,\n", goField, v.num)
		}
	}
	for cField, goField := range languageRefs {
		v, ok := e.file.lang[cField]
		if !ok || v.ref == "" {
			continue
		}
		goVar, ok := refToGoVar[v.ref]
		if !ok || e.array(v.ref) == nil {
			continue
		}
		e.printf("\t%s: %s,\n", goField, goVar)
	}
	if v, ok := e.file.lang["name"]; ok && v.isStr {
		e.printf("\tName: %q,\n", v.str)
	}
	if _, ok := e.file.lexFns["ts_lex"]; ok {
		e.printf("\tLexFn: tsLex,\n")
	}
	if _, ok := e.file.lexFns["ts_lex_keywords"]; ok {
		e.printf("\tKeywordLexFn: tsLexKeywords,\n")
	}
	if e.array("ts_external_scanner_states") != nil {
		e.printf("\tExternalScannerStates: externalScannerStates,\n")
	}
	if e.array("ts_external_scanner_symbol_map") != nil {
		e.printf("\tExternalScannerSymbol: externalScannerSymbolMap,\n")
	}
	if v, ok := e.file.lang["metadata"]; ok && v.elems != nil {
		e.printf("\tMetadata: ts.LanguageMetadata{MajorVersion: %d, MinorVersion: %d, PatchVersion: %d},\n",
			v.elems["major_version"], v.elems["minor_version"], v.elems["patch_version"])
	}
	e.printf("}\n\n")

	e.printf("// Language returns the %s grammar.\n", e.file.languageName)
	e.printf("func Language() *ts.Language {\n")
	if e.file.hasScanner {
		e.printf("\tlanguage.Scanner = scanner{}\n")
	}
	e.printf("\treturn &language\n")
	e.printf("}\n")
}
